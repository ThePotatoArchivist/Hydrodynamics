package archives.tater.hydrodynamics.client.datagen;

import net.fabricmc.fabric.api.datagen.v1.FabricPackOutput;
import net.fabricmc.fabric.api.datagen.v1.provider.FabricDynamicRegistryProvider;

import net.minecraft.core.HolderLookup;
import net.minecraft.core.registries.Registries;

import java.util.concurrent.CompletableFuture;

public class ModRegistryProvider extends FabricDynamicRegistryProvider {
    public ModRegistryProvider(FabricPackOutput output, CompletableFuture<HolderLookup.Provider> registriesFuture) {
        super(output, registriesFuture);
    }

    @Override
    protected void configure(HolderLookup.Provider registries, Entries entries) {
        entries.addAll(registries.lookupOrThrow(Registries.CONTEXT_INT_PROVIDER));
        entries.addAll(registries.lookupOrThrow(Registries.PREDICATE));
    }

    @Override
    public String getName() {
        return "Dynamic Registries";
    }
}
